def get_repeat_response(person, topic, repeat_count):
    """인물의 성격과 반복 횟수에 맞는 재질문 반응을 고른다."""
    responses = REPEAT_RESPONSES[person]
    index = min(max(repeat_count - 2, 0), len(responses) - 1)
    response = responses[index]

    if person == "김동율":
        if topic.startswith("haesung"):
            if repeat_count == 2:
                response = (
                    "해성호 사고에 관해서는 이미 말씀드렸습니다. "
                    "제게 현장 책임이 일부 있었지만, 책임이 한 "
                    "사람에게 집중된 과정은 따로 보셔야 합니다."
                )
            else:
                response = (
                    "같은 과거를 몇 번 되묻는다고 기록이 달라지지는 "
                    "않습니다. 더 확인할 내용이 있다면 당시 기록을 "
                    "가져오십시오."
                )
        elif topic == "alibi" and repeat_count == 2:
            response = (
                "저녁 일정 이후에는 혼자 있었습니다. 최종인 객실 "
                "쪽으로 가지 않았다는 제 답은 달라지지 않습니다."
            )
        elif topic == "relationship" and repeat_count >= 3:
            response = (
                "최종인을 원망한 건 부정하지 않습니다. 하지만 그 "
                "감정만으로 사건 당일 행동까지 단정하지 마십시오."
            )

    return f"> “{response}”"


